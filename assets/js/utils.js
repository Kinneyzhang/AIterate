export function escapeHtml(text) {
  return String(text || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

const DOMPURIFY_ALLOWED = [
  // 块级
  'h1', 'h2', 'h3', 'h4', 'h5', 'h6',
  'p', 'br', 'hr', 'pre', 'blockquote',
  // 内联
  'strong', 'em', 'b', 'i', 'u', 's', 'del', 'ins',
  'a', 'code', 'img', 'span', 'div',
  // 列表
  'ul', 'ol', 'li',
  // 表格
  'table', 'thead', 'tbody', 'tfoot', 'tr', 'th', 'td',
  // 上标/下标
  'sup', 'sub',
];

const DOMPURIFY_ATTRS = [
  // 链接
  'href', 'title', 'target', 'rel',
  // 图片
  'src', 'alt', 'width', 'height',
  // 通用
  'class', 'id', 'style',
  // 上标/下标引用
  'role', 'aria-label', 'data-*',
];

export function renderMarkdown(md) {
  if (typeof marked === 'undefined') return escapeHtml(md);
  const raw = marked.parse(String(md || ''));
  if (typeof DOMPurify !== 'undefined') {
    return DOMPurify.sanitize(raw, { ALLOWED_TAGS: DOMPURIFY_ALLOWED, ALLOWED_ATTR: DOMPURIFY_ATTRS });
  }
  return raw;
}

